import { useEffect, useRef, useState } from 'react';
import { formatDay } from '../../engine/index';
import { useCmoNote, useDayAssessment, useMission } from '../../state/MissionContext';
import { StatusBadge } from '../components/StatusBadge';

export function CmoNoteScreen() {
  const { selectedDay, stepDay, input } = useMission();
  const day = useDayAssessment();
  const draft = useCmoNote();
  const [text, setText] = useState(draft);
  const [edited, setEdited] = useState(false);
  const [msg, setMsg] = useState<string | null>(null);
  const ref = useRef<HTMLTextAreaElement>(null);

  useEffect(() => {
    if (!edited) setText(draft);
  }, [draft, edited]);

  useEffect(() => setMsg(null), [selectedDay]);

  async function copy() {
    try {
      if (navigator.clipboard?.writeText) {
        await navigator.clipboard.writeText(text);
      } else {
        ref.current?.select();
        if (!document.execCommand('copy')) throw new Error('copy failed');
      }
      setMsg('Copied');
    } catch {
      setMsg('Copy failed — select the text and copy manually.');
    }
  }

  function download() {
    const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `baseline-cmo-note-${formatDay(selectedDay)}.txt`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
    setMsg('Downloaded');
  }

  return (
    <section className="screen" aria-labelledby="note-title">
      <div className="day-nav">
        <button type="button" className="btn btn--ghost" onClick={() => stepDay(-1)} disabled={selectedDay <= -30} aria-label="Previous day">
          ← Prev
        </button>
        <h2 id="note-title">CMO note · {formatDay(selectedDay)}</h2>
        <button type="button" className="btn btn--ghost" onClick={() => stepDay(1)} disabled={selectedDay >= input.currentDay} aria-label="Next day">
          Next →
        </button>
      </div>
      <div className="overall">
        <StatusBadge status={day.overall} large />
        <p className="overall__summary">
          {day.cmoSuggested ? 'BASELINE suggests sharing this with your crew medical officer.' : 'Nothing needs reporting today'}
        </p>
      </div>
      <p className="notice">Draft generated by a prototype from SIMULATED data. Review before sending. BASELINE does not diagnose.</p>
      <label htmlFor="cmo-note" className="visually-hidden">
        CMO note draft
      </label>
      <textarea
        id="cmo-note"
        ref={ref}
        className="note-text"
        rows={20}
        value={text}
        onChange={(e) => {
          setText(e.target.value);
          setEdited(true);
        }}
      />
      <div className="note-actions">
        <button type="button" className="btn btn--primary" onClick={copy}>
          Copy note
        </button>
        <button type="button" className="btn btn--ghost" onClick={download}>
          Download .txt
        </button>
        {edited && (
          <button
            type="button"
            className="btn btn--ghost"
            onClick={() => {
              setEdited(false);
              setText(draft);
            }}
          >
            Reset to draft
          </button>
        )}
        {msg && (
          <span className="success" role="status">
            {msg}
          </span>
        )}
      </div>
    </section>
  );
}
